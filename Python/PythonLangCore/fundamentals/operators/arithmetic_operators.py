print(5 + 3)  # 8
print(5 - 3)  # 2
print(5 * 3)  # 15

print(6 / 3)  # 2.0
print(5 / 3)  # 1.6666666666666667

#   floor division
print(5 / 2)  # 2.5
print(5 // 2) # 2

# Remainder and exponentiation
print(10 % 3)  # 1
print(5 ** 3) # 125 = 5^3

print(-10 // 3)  # -4 because -10 / 3 = -3.333..., and floor division rounds down to the nearest whole number, which is -4.