x = 9
print(type(x))  # <class 'int'>
msg = "Hello, World!"

print(type(msg))  # <class 'str'>
y=5.5

print(type(y))  # <class 'float'>

is_python_fun = True
print(type(is_python_fun))  # <class 'bool'>
is_python_fun = False
print(type(is_python_fun))  # <class 'bool'>

course_status=None
print(type(course_status))  # <class 'NoneType'>

print(type(print))  # <class 'builtin_function_or_method'>
print(x, msg, y, is_python_fun, course_status)  # 9 Hello, World! 5.5 False None