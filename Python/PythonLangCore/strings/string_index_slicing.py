s = "Classic Cars"

# Accessing Individual characters by index
print(s[0])
print(s[-1])
print(s[-2])

# Slicing
print(s[1:7])# s:e
print(s[:7])# start index defaults to 0
print(s[8:])


print(s[:])
print(s[::1])
print(s[::2])
print(s[::-1])

print(s[-4:])

# SLICING
s= "Cars"
print(s[0:9999])
print(s[9999999:])

# INDEXED BASED ACCESS
print(s[999])